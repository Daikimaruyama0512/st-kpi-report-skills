# ─── API ヘルパー ───────────────────────────────
def api_post(url, body):
    data = json.dumps(body, ensure_ascii=False).encode('utf-8')
    req = urllib.request.Request(url, data=data, headers={
        "Authorization": f"Bearer {token}",
        "Content-Type": "application/json",
    })
    with urllib.request.urlopen(req) as r:
        return json.loads(r.read().decode('utf-8'))

def api_get(url):
    req = urllib.request.Request(url, headers={"Authorization": f"Bearer {token}"})
    with urllib.request.urlopen(req) as r:
        return json.loads(r.read().decode('utf-8'))

def values_batch_update(data_list):
    url = f"https://sheets.googleapis.com/v4/spreadsheets/{SPREADSHEET_ID}/values:batchUpdate"
    return api_post(url, {"valueInputOption": "USER_ENTERED", "data": data_list})

def batch_format(requests):
    url = f"https://sheets.googleapis.com/v4/spreadsheets/{SPREADSHEET_ID}:batchUpdate"
    return api_post(url, {"requests": requests})

def rgb(r, g, b):
    return {"red": r/255, "green": g/255, "blue": b/255}

def cell_color(sheet_id, row, col, color, end_row=None, end_col=None):
    return {
        "repeatCell": {
            "range": {
                "sheetId": sheet_id,
                "startRowIndex": row, "endRowIndex": end_row or row+1,
                "startColumnIndex": col, "endColumnIndex": end_col or col+1
            },
            "cell": {"userEnteredFormat": {"backgroundColor": color}},
            "fields": "userEnteredFormat.backgroundColor"
        }
    }

def header_format(sheet_id, row_count, col_count, color, bold=True):
    return {
        "repeatCell": {
            "range": {"sheetId": sheet_id, "startRowIndex": 0, "endRowIndex": row_count,
                      "startColumnIndex": 0, "endColumnIndex": col_count},
            "cell": {"userEnteredFormat": {
                "backgroundColor": color,
                "textFormat": {"bold": bold, "fontSize": 10},
                "verticalAlignment": "MIDDLE",
                "wrapStrategy": "WRAP",
            }},
            "fields": "userEnteredFormat(backgroundColor,textFormat,verticalAlignment,wrapStrategy)"
        }
    }

def set_col_width(sheet_id, col, width_px):
    return {
        "updateDimensionProperties": {
            "range": {"sheetId": sheet_id, "dimension": "COLUMNS",
                      "startIndex": col, "endIndex": col+1},
            "properties": {"pixelSize": width_px},
            "fields": "pixelSize"
        }
    }

def set_row_height(sheet_id, start_row, end_row, height_px):
    return {
        "updateDimensionProperties": {
            "range": {"sheetId": sheet_id, "dimension": "ROWS",
                      "startIndex": start_row, "endIndex": end_row},
            "properties": {"pixelSize": height_px},
            "fields": "pixelSize"
        }
    }

def freeze_rows(sheet_id, count):
    return {"updateSheetProperties": {"properties": {
        "sheetId": sheet_id,
        "gridProperties": {"frozenRowCount": count}
    }, "fields": "gridProperties.frozenRowCount"}}

def wrap_all(sheet_id, num_rows, num_cols):
    return {
        "repeatCell": {
            "range": {"sheetId": sheet_id, "startRowIndex": 0, "endRowIndex": num_rows,
                      "startColumnIndex": 0, "endColumnIndex": num_cols},
            "cell": {"userEnteredFormat": {"wrapStrategy": "WRAP", "verticalAlignment": "TOP"}},
            "fields": "userEnteredFormat(wrapStrategy,verticalAlignment)"
        }
    }

