# ─────────────────────────────────────────
# 4. データを一括書き込み
# ─────────────────────────────────────────
print("3. データ書き込み中...")

write_data = []
for tab_name in tabs_to_create:
    rows = TAB_DATA.get(tab_name)
    if not rows:
        print(f"   スキップ（データ未定義）: {tab_name}")
        continue
    write_data.append({
        "range": f"'{tab_name}'!A1",
        "values": rows,
    })

if write_data:
    res = api_post(
        f"https://sheets.googleapis.com/v4/spreadsheets/{SPREADSHEET_ID}/values:batchUpdate",
        {
            "valueInputOption": "USER_ENTERED",
            "data": write_data,
        }
    )
    total_cells = res.get('totalUpdatedCells', '?')
    print(f"   書き込み完了: {total_cells} セル更新")

