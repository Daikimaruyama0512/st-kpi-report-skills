# ─────────────────────────────────────────
# 2. タブ（シート）を新規追加
# ─────────────────────────────────────────
print("2. タブ追加中...")
add_requests = [{"addSheet": {"properties": {"title": t}}} for t in tabs_to_create]
batch_res = api_post(
    f"https://sheets.googleapis.com/v4/spreadsheets/{SPREADSHEET_ID}:batchUpdate",
    {"requests": add_requests}
)

# sheetId を title → id のマップに変換
sheet_id_map = {}
for reply in batch_res.get('replies', []):
    props = reply.get('addSheet', {}).get('properties', {})
    if props:
        sheet_id_map[props['title']] = props['sheetId']

print(f"   作成済み: {list(sheet_id_map.keys())}")


