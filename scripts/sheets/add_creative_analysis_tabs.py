# ─── API ヘルパー ───────────────────────────────
def api_post(url, body):
    data = json.dumps(body, ensure_ascii=False).encode('utf-8')
    req = urllib.request.Request(url, data=data, headers={
        "Authorization": f"Bearer {token}",
        "Content-Type": "application/json",
    })
    with urllib.request.urlopen(req) as r:
        return json.loads(r.read().decode('utf-8'))

def api_get(url):
    req = urllib.request.Request(url, headers={"Authorization": f"Bearer {token}"})
    with urllib.request.urlopen(req) as r:
        return json.loads(r.read().decode('utf-8'))

def values_update(tab, data):
    url = f"https://sheets.googleapis.com/v4/spreadsheets/{SPREADSHEET_ID}/values:batchUpdate"
    return api_post(url, {"valueInputOption": "USER_ENTERED", "data": [{"range": f"'{tab}'!A1", "values": data}]})

def batch_format(requests):
    url = f"https://sheets.googleapis.com/v4/spreadsheets/{SPREADSHEET_ID}:batchUpdate"
    return api_post(url, {"requests": requests})

def rgb(r, g, b): return {"red": r/255, "green": g/255, "blue": b/255}

def section_header(sheet_id, row, num_cols, bg_color, font_size=11):
    return {
        "repeatCell": {
            "range": {"sheetId": sheet_id, "startRowIndex": row, "endRowIndex": row+1,
                      "startColumnIndex": 0, "endColumnIndex": num_cols},
            "cell": {"userEnteredFormat": {
                "backgroundColor": bg_color,
                "textFormat": {"bold": True, "fontSize": font_size, "foregroundColor": rgb(255,255,255)},
                "verticalAlignment": "MIDDLE", "wrapStrategy": "WRAP",
            }},
            "fields": "userEnteredFormat(backgroundColor,textFormat,verticalAlignment,wrapStrategy)"
        }
    }

def sub_header(sheet_id, row, num_cols, bg_color=None):
    bg = bg_color or rgb(215, 225, 245)
    return {
        "repeatCell": {
            "range": {"sheetId": sheet_id, "startRowIndex": row, "endRowIndex": row+1,
                      "startColumnIndex": 0, "endColumnIndex": num_cols},
            "cell": {"userEnteredFormat": {
                "backgroundColor": bg,
                "textFormat": {"bold": True},
                "wrapStrategy": "WRAP",
            }},
            "fields": "userEnteredFormat(backgroundColor,textFormat,wrapStrategy)"
        }
    }

def wrap_all(sheet_id, num_rows, num_cols):
    return {
        "repeatCell": {
            "range": {"sheetId": sheet_id, "startRowIndex": 0, "endRowIndex": num_rows,
                      "startColumnIndex": 0, "endColumnIndex": num_cols},
            "cell": {"userEnteredFormat": {"wrapStrategy": "WRAP", "verticalAlignment": "TOP"}},
            "fields": "userEnteredFormat(wrapStrategy,verticalAlignment)"
        }
    }

def col_width(sheet_id, col, px):
    return {
        "updateDimensionProperties": {
            "range": {"sheetId": sheet_id, "dimension": "COLUMNS", "startIndex": col, "endIndex": col+1},
            "properties": {"pixelSize": px}, "fields": "pixelSize"
        }
    }

def cell_bg(sheet_id, row, col, color, end_row=None, end_col=None):
    return {
        "repeatCell": {
            "range": {"sheetId": sheet_id,
                      "startRowIndex": row, "endRowIndex": end_row or row+1,
                      "startColumnIndex": col, "endColumnIndex": end_col or col+1},
            "cell": {"userEnteredFormat": {"backgroundColor": color}},
            "fields": "userEnteredFormat.backgroundColor"
        }
    }

